#!/usr/bin/env python3
"""Join per-cell netlists into the sky130_efx_lvdig library netlists, laid out
as the PDK's libs.ref/sky130_fd_sc_hd/ (2026-11-08):

    scripts/gen_lib_netlist.py cdl   OUT.cdl   lvs/schematic/<cell>.spice ...
    scripts/gen_lib_netlist.py spice_<none|c|rc> OUT.spice REF.cdl lvs/pex_<mode>/<cell>.spice ...

cdl:   the schematic (source) netlist, as hd's cdl/: each cell's .subckt from
       xschem (the LVS schematic netlists). Written in SPICE syntax, which
       Netgen and ngspice both read.
spice_none, spice_c, spice_rc: the layout-extracted netlist, as hd's spice/
       (devices only), or with parasitic C, or with parasitic R and C. Magic
       extracts a flattened copy of each cell (.subckt name <cell>_flat; the
       suffix is removed). Magic orders a cell's ports by its pin labels' port
       numbers, so each .subckt line is rewritten to the cdl's port order (the
       netlists are then interchangeable in a testbench); the port names must
       be the same set.

Run by `make libcdl` / `make libspice [PEX=none|c|rc]`. Lines that depend on the checkout
(`** sch_path: /abs/path`) are dropped, so an output changes only when a cell
does. Cells are written in name order; each input must hold one .subckt.
"""
import os
import re
import sys

NOTICE_LINES = ('* Copyright (c) 2026 Eric Fogleman',
                '* SPDX-License-Identifier: Apache-2.0',
                '* Derived from SkyWater sky130_fd_sc_hd (Apache-2.0); see NOTICE')
COMMON = """\
* Cell topologies and device sizes are derived from SkyWater's sky130_fd_sc_hd
* (Apache-2.0; see NOTICE). Layouts are independent.
*
* Not interchangeable with the PDK's sky130_fd_sc_hd netlists:
*  - device widths are on the efx lambda grid (L = 0.18 um; e.g. 0.42 -> 0.45,
*    0.65 -> 0.63, 1.00 -> 1.08), conb_1's resistors W 0.45 x L 0.54
*  - ports: logic pins, then VGND VNB VPB VPWR (hd: power pins in between),
*    so instantiate by the .subckt lines below, not by hd's pin order
* Devices are sky130_fd_pr models; include the PDK model library first, e.g.
*   .lib $PDK_ROOT/sky130A/libs.tech/ngspice/sky130.lib.spice tt
"""
HEADER = {
    'cdl': """\
* sky130_efx_lvdig standard cells: schematic (source) netlist, one .subckt per
* cell from the xschem schematics in xschem/ (generated by `make libcdl`; don't
* edit). The reference side of LVS, as the PDK's cdl/. Layout-extracted
* netlists: spice/sky130_efx_lvdig{,_c,_rc}.spice (make libspice PEX=none|c|rc).
*
""" + COMMON,
    'spice_none': """\
* sky130_efx_lvdig standard cells: layout-extracted netlist, devices only (as
* the PDK's spice/), one .subckt per cell from the layouts in mag/ (generated
* by `make libspice PEX=none`; don't edit).
* Magic on a flattened copy of each cell (every device has its own
* source/drain area and perimeter). Internal nets have Magic's coordinate
* names (a_<x>_<y>#). Ports are in the same order as cdl/sky130_efx_lvdig.cdl
* (the schematic netlist), so the netlists can be swapped in a testbench.
*
""" + COMMON,
    'spice_c': """\
* sky130_efx_lvdig standard cells: layout-extracted netlist with parasitic
* capacitance, one .subckt per cell from the layouts in mag/ (generated by
* `make libspice` / `PEX=c`; don't edit): every non-zero node-to-node and
* node-to-substrate capacitance (ext2spice cthresh 0; the substrate node is
* VNB), no resistance.
* Magic on a flattened copy of each cell (every device has its own
* source/drain area and perimeter). Internal nets have Magic's coordinate
* names (a_<x>_<y>#). Ports are in the same order as cdl/sky130_efx_lvdig.cdl
* (the schematic netlist), so the netlists can be swapped in a testbench.
*
""" + COMMON,
    'spice_rc': """\
* sky130_efx_lvdig standard cells: layout-extracted netlist with parasitic R
* and C, one .subckt per cell from the layouts in mag/ (generated by
* `make libspice PEX=rc`; don't edit): extresist (all nets, tolerance 10) for
* wiring and contact resistance, ext2spice cthresh 0 for every non-zero
* capacitance (substrate node VNB). Nets are split at the resistors: Magic
* names the pieces <net>.n<k> (wiring) and <net>.t<k> (device terminals).
* Magic on a flattened copy of each cell (every device has its own
* source/drain area and perimeter). Internal nets have Magic's coordinate
* names (a_<x>_<y>#). Ports are in the same order as cdl/sky130_efx_lvdig.cdl
* (the schematic netlist), so the netlists can be swapped in a testbench.
*
""" + COMMON,
}


def cell_name(path):
    return re.sub(r'\.spice$', '', os.path.basename(path))


def subckt_lines(text, path):
    found = re.findall(r'^\.subckt \S+.*$', text, re.M)
    if len(found) != 1:
        sys.exit(f'{path}: expected one .subckt, found {len(found)}')
    return found[0]


def main(mode, out, ref, inputs):
    ports = {}
    if ref:
        for ln in open(ref):
            if ln.startswith('.subckt '):
                t = ln.split()
                ports[t[1]] = t[2:]
    parts = []
    for path in sorted(inputs, key=cell_name):
        # the schematics' copyright notice (copyright.sym) is written once at
        # the top of the library instead of before every cell
        keep = [ln for ln in open(path).read().splitlines()
                if not ln.startswith('** sch_path:') and ln.strip() != '.end'
                and ln not in NOTICE_LINES
                and not ln.startswith('* NGSPICE file created from')]
        if mode.startswith('spice'):
            # Magic flags some substrate caps '$ **FLOATING' although every
            # flagged node here reaches a source/drain; Netgen reads the '$'
            # as an element.
            # Zero-valued caps (cthresh 0) are dropped.
            keep = [re.sub(r'\s+\$\s*\*\*FLOATING\s*$', '', ln) for ln in keep]
            keep = [ln for ln in keep if not re.fullmatch(r'C\d+ \S+ \S+ 0', ln)]
        text = '\n'.join(keep).strip('\n')
        line = subckt_lines(text, path)
        if mode.startswith('spice'):
            name, have = line.split()[1], line.split()[2:]
            name = re.sub(r'_flat$', '', name)
            want = ports.get(name)
            if want is None:
                sys.exit(f'{path}: {name} is not in {ref}')
            if sorted(have) != sorted(want):
                sys.exit(f'{path}: ports {have} differ from {ref}: {want}')
            text = text.replace(line, f'.subckt {name} ' + ' '.join(want), 1)
        parts.append(text)
    with open(out, 'w') as f:
        f.write('\n'.join(NOTICE_LINES) + '\n*\n' + HEADER[mode] + '\n' + '\n\n'.join(parts) + '\n')
    print(f'wrote {out}: {len(parts)} cells')


if __name__ == '__main__':
    a = sys.argv[1:]
    if len(a) >= 3 and a[0] == 'cdl':
        main('cdl', a[1], None, a[2:])
    elif len(a) >= 4 and a[0] in ('spice_none', 'spice_c', 'spice_rc'):
        main(a[0], a[1], a[2], a[3:])
    else:
        sys.exit(__doc__)
