#!/usr/bin/env python3
"""Write xschem/sky130_efx_lvdig__allcells.sch: one instance of every logic
cell placed in mag/sky130_efx_lvdig__allcells.mag, for `make lvs
CELL=sky130_efx_lvdig__allcells` (2026-11-07).

The cell list is read from ROWS in scripts/mag_build_allcells.tcl, so the
two stay in step; rerun this after changing ROWS. Tap cells are left out:
they have no devices and extraction drops them. Every logic pin gets its own
net (<instance>_<pin>). Power follows what the layout extracts to: VGND and
VNB are one net (the substrate, VSUBS in the layout), and VPWR/VPB are one
net per pair of rows that share a VPWR rail and n-well (VPWR_R01, VPWR_R23,
...), since nothing joins the row pairs.

    python3 scripts/gen_allcells_sch.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PREFIX = 'sky130_efx_lvdig__'
DX, DY = 360, 400          # instance pitch in a row, row pitch

tcl = (ROOT / 'scripts/mag_build_allcells.tcl').read_text()
rows_txt = re.search(r'set ROWS \{(.*?)\n\}', tcl, re.S).group(1)
rows = [r.split() for r in re.findall(r'\{([^{}]*)\}', rows_txt)]

PIN = re.compile(r'^B 5 (\S+) (\S+) (\S+) (\S+) \{name=(\w+)', re.M)

out = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', 'K {}', 'V {}', 'S {}', 'E {}',
       'T {Generated by scripts/gen_allcells_sch.py from ROWS in scripts/mag_build_allcells.tcl;'
       ' do not edit by hand.} 0 -200 0 0 0.4 0.4 {}']
n_inst = n_lab = 0
for r, row in enumerate(rows):
    vpwr = f'VPWR_R{r // 2 * 2}{r // 2 * 2 + 1}'
    y = r * DY
    x = 0
    for c in row:
        if c.startswith('tap'):
            continue
        sym = ROOT / 'xschem' / f'{PREFIX}{c}.sym'
        inst = f'x{c}'
        out.append(f'C {{{sym.name}}} {x} {y} 0 0 {{name={inst} VGND=VGND VNB=VGND '
                   f'VPB={vpwr} VPWR={vpwr} prefix={PREFIX}}}')
        n_inst += 1
        for m in PIN.finditer(sym.read_text()):
            x0, y0, x1, y1 = map(float, m.group(1, 2, 3, 4))
            px, py = x + (x0 + x1) / 2, y + (y0 + y1) / 2
            n_lab += 1
            out.append(f'C {{devices/lab_pin.sym}} {px:g} {py:g} 0 {0 if px < x else 1} '
                       f'{{name=l{n_lab} lab={inst}_{m.group(5)}}}')
        x += DX
# Top-level ports for the power nets, matching the layout's port labels
# (scripts/mag_build_allcells.tcl): netgen fails the pin check of a portless
# top cell once dfxtp_2 is in (2026-11-07).
pwr = ['VGND'] + [f'VPWR_R{k}{k + 1}' for k in range(0, len(rows), 2)]
for k, net in enumerate(pwr):
    out.append(f'C {{devices/iopin.sym}} -200 {k * 40} 0 0 {{name=p{k + 1} lab={net}}}')
dst = ROOT / 'xschem' / f'{PREFIX}allcells.sch'
# copyright/license notice (xschem/copyright.sym, place=header), above the ports
out.append('C {copyright.sym} -200 -200 0 0 {name=s1 place=header value="'
           '* Copyright (c) 2026 Eric Fogleman\n* SPDX-License-Identifier: Apache-2.0\n'
           '* Derived from SkyWater sky130_fd_sc_hd (Apache-2.0); see NOTICE"}')
dst.write_text('\n'.join(out) + '\n')
print(f'wrote {dst.relative_to(ROOT)}: {n_inst} cells, {n_lab} pin labels')
